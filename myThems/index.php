// Two-Factor Authentication (Simple Version)
function mpt_two_factor_auth($user, $username, $password) {
    if (!empty($username) && !empty($password)) {
        $user = get_user_by('login', $username);
        
        if ($user && wp_check_password($password, $user->user_pass, $user->ID)) {
            // Check if 2FA is enabled for user
            $two_factor_enabled = get_user_meta($user->ID, 'mpt_two_factor_enabled', true);
            
            if ($two_factor_enabled) {
                // Generate and send OTP
                $otp = rand(100000, 999999);
                update_user_meta($user->ID, 'mpt_two_factor_otp', $otp);
                update_user_meta($user->ID, 'mpt_two_factor_otp_expiry', time() + 300); // 5 minutes
                
                // Send OTP via email
                wp_mail(
                    $user->user_email,
                    __('Your Login Verification Code', 'mpt'),
                    sprintf(__('Your verification code is: %d', 'mpt'), $otp)
                );
                
                // Redirect to OTP verification page
                wp_redirect(home_url('/verify-otp/'));
                exit;
            }
        }
    }
    
    return $user;
}
add_filter('authenticate', 'mpt_two_factor_auth', 30, 3);

