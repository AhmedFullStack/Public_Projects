// Accordion Shortcode
function mpt_accordion_shortcode($atts, $content = null) {
    static $accordion_instance = 0;
    $accordion_instance++;
    
    $atts = shortcode_atts([
        'multiple' => 'false',
        'class'    => '',
    ], $atts);
    
    preg_match_all('/\[accordion_item title="([^\"]+)"\](.*?)\[\/accordion_item\]/s', $content, $matches);
    
    if (empty($matches[1])) {
        return $content;
    }
    
    $accordion_id = 'accordion-' . $accordion_instance;
    $output = '<div class="accordion ' . esc_attr($atts['class']) . '" id="' . esc_attr($accordion_id) . '">';
    
    foreach ($matches[1] as $i => $title) {
        $item_id = sanitize_title($title) . '-' . $i;
        $show = $i === 0 ? ' show' : '';
        $collapsed = $i === 0 ? '' : ' collapsed';
        
        $output .= '
        <div class="card">
            <div class="card-header" id="heading-' . $item_id . '">
                <h5 class="mb-0">
                    <button class="btn btn-link' . $collapsed . '" type="button" data-toggle="collapse" 
                            data-target="#collapse-' . $item_id . '" aria-expanded="' . ($i === 0 ? 'true' : 'false') . '" 
                            aria-controls="collapse-' . $item_id . '">
                        ' . esc_html($title) . '
                    </button>
                </h5>
            </div>
            <div id="collapse-' . $item_id . '" class="collapse' . $show . '" 
                 aria-labelledby="heading-' . $item_id . '" data-parent="#' . $accordion_id . '">
                <div class="card-body">
                    ' . do_shortcode($matches[2][$i]) . '
                </div>
            </div>
        </div>';
    }
    
    $output .= '</div>';
    
    return $output;
}
