// Tabs Shortcode
function mpt_tabs_shortcode($atts, $content = null) {
    static $tab_instance = 0;
    $tab_instance++;
    
    $atts = shortcode_atts([
        'type'  => 'tabs',
        'class' => '',
    ], $atts);
    
    // Extract tab titles
    preg_match_all('/\[tab title="([^\"]+)"\](.*?)\[\/tab\]/s', $content, $matches);
    
    if (empty($matches[1])) {
        return $content;
    }
    
    $tab_nav = '<ul class="nav nav-' . esc_attr($atts['type']) . '" role="tablist">';
    $tab_content = '<div class="tab-content">';
    
    foreach ($matches[1] as $i => $title) {
        $active = $i === 0 ? ' active' : '';
        $id = 'tab-' . $tab_instance . '-' . sanitize_title($title);
        
        $tab_nav .= sprintf(
            '<li class="nav-item">
                <a class="nav-link%s" id="%s" data-toggle="tab" href="#%s-content" role="tab">%s</a>
            </li>',
            $active,
            esc_attr($id),
            esc_attr($id),
            esc_html($title)
        );
        
        $tab_content .= sprintf(
            '<div class="tab-pane fade%s" id="%s-content" role="tabpanel">%s</div>',
            $active ? ' show active' : '',
            esc_attr($id),
            do_shortcode($matches[2][$i])
        );
    }
    
    $tab_nav .= '</ul>';
    $tab_content .= '</div>';
    
    return '<div class="mpt-tabs ' . esc_attr($atts['class']) . '">' . $tab_nav . $tab_content . '</div>';
}
add_shortcode('tabs', 'mpt_tabs_shortcode');

