// Breadcrumbs
function mpt_breadcrumbs() {
    if (is_front_page()) {
        return;
    }
    
    echo '<nav class="breadcrumb" aria-label="Breadcrumb">';
    echo '<ol class="breadcrumb-list">';
    echo '<li class="breadcrumb-item"><a href="' . home_url() . '">' . __('Home', 'mpt') . '</a></li>';
    
    if (is_category() || is_single()) {
