/**
 * My Premium Theme Setup
 */
function mpt_setup() {
    // Load Text Domain for Translation
    load_theme_textdomain('mpt', MPT_THEME_DIR . '/languages');
    
    // Add Theme Supports
    add_theme_support('title-tag');
    add_theme_support('post-thumbnails');
    add_theme_support('html5', [
        'search-form', 'comment-form', 'comment-list', 'gallery', 'caption',
        'style', 'script', 'navigation-widgets'
    ]);
    add_theme_support('responsive-embeds');
    add_theme_support('customize-selective-refresh-widgets');
    add_theme_support('align-wide');
    add_theme_support('editor-styles');
    add_editor_style('assets/css/editor-style.css');
    add_theme_support('wp-block-styles');
    
    // Custom Logo
    add_theme_support('custom-logo', [
        'height'      => 100,
        'width'       => 400,
        'flex-height' => true,
        'flex-width'  => true,
    ]);
    
    // Custom Background
    add_theme_support('custom-background', [
        'default-color' => 'ffffff',
        'default-image' => '',
    ]);
    
    // Feed Links
    add_theme_support('automatic-feed-links');
    
    // WooCommerce Support
    add_theme_support('woocommerce');
    add_theme_support('wc-product-gallery-zoom');
    add_theme_support('wc-product-gallery-lightbox');
    add_theme_support('wc-product-gallery-slider');
    
    // Register Navigation Menus
    register_nav_menus([
        'primary'           => __('Primary Menu', 'mpt'),
        'secondary'         => __('Secondary Menu', 'mpt'),
        'mobile'           => __('Mobile Menu', 'mpt'),
        'footer'           => __('Footer Menu', 'mpt'),
        'social'           => __('Social Menu', 'mpt'),
        'top_bar'          => __('Top Bar Menu', 'mpt'),
        'mega_menu'        => __('Mega Menu', 'mpt'),
    ]);
    
    // Image Sizes
    add_image_size('mpt_featured_large', 1200, 800, true);
    add_image_size('mpt_featured_medium', 768, 512, true);
    add_image_size('mpt_featured_small', 400, 267, true);
    add_image_size('mpt_thumbnail', 150, 150, true);
    add_image_size('mpt_square', 400, 400, true);
    add_image_size('mpt_portfolio', 800, 600, true);
    add_image_size('mpt_team', 500, 500, true);
    
    // Theme Activation
    if (is_admin() && isset($_GET['activated'])) {
        mpt_theme_activation();
    }
}
add_action('after_setup_theme', 'mpt_setup');

/**
 * Enqueue Theme Assets
 */
function mpt_enqueue_assets() {
    $theme_version = wp_get_theme()->get('Version');
    
    // Google Fonts
    wp_enqueue_style('mpt-google-fonts', 'https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700;800;900&family=Poppins:wght@300;400;500;600;700;800&display=swap', [], null);
    
    // Font Awesome
    wp_enqueue_style('font-awesome', 'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/css/all.min.css', [], '6.4.0');
    
    // Bootstrap CSS
    wp_enqueue_style('bootstrap', 'https://cdn.jsdelivr.net/npm/bootstrap@5.3.0/dist/css/bootstrap.min.css', [], '5.3.0');
    
    // Main Stylesheet
    wp_enqueue_style('mpt-style', MPT_ASSETS_URI . '/css/main.css', ['bootstrap', 'font-awesome'], $theme_version);
    
    // RTL Support
    if (is_rtl()) {
        wp_enqueue_style('mpt-rtl', MPT_ASSETS_URI . '/css/rtl.css', ['mpt-style'], $theme_version);
    }
    
    // Dark Mode CSS
    if (get_theme_mod('dark_mode_enable', false)) {
        wp_enqueue_style('mpt-dark-mode', MPT_ASSETS_URI . '/css/dark-mode.css', ['mpt-style'], $theme_version);
    }
    
    // Custom CSS from Customizer
    wp_add_inline_style('mpt-style', mpt_custom_css());
    
    // JavaScript Libraries
    wp_enqueue_script('jquery');
    wp_enqueue_script('bootstrap-bundle', 'https://cdn.jsdelivr.net/npm/bootstrap@5.3.0/dist/js/bootstrap.bundle.min.js', ['jquery'], '5.3.0', true);
    
    // Isotope for Filterable Grids
    if (is_post_type_archive('portfolio') || is_page_template('template-portfolio.php')) {
        wp_enqueue_script('isotope', 'https://unpkg.com/isotope-layout@3.0.6/dist/isotope.pkgd.min.js', ['jquery'], '3.0.6', true);
    }
    
    // Owl Carousel
    if (is_front_page() || is_page_template('template-home.php')) {
        wp_enqueue_style('owl-carousel', 'https://cdnjs.cloudflare.com/ajax/libs/OwlCarousel2/2.3.4/assets/owl.carousel.min.css', [], '2.3.4');
        wp_enqueue_script('owl-carousel', 'https://cdnjs.cloudflare.com/ajax/libs/OwlCarousel2/2.3.4/owl.carousel.min.js', ['jquery'], '2.3.4', true);
    }
    
    // Main Theme JavaScript
    wp_enqueue_script('mpt-main', MPT_ASSETS_URI . '/js/main.js', ['jquery', 'bootstrap-bundle'], $theme_version, true);
    
    // AJAX Configuration
    wp_localize_script('mpt-main', 'mpt_ajax', [
        'ajax_url'          => admin_url('admin-ajax.php'),
        'nonce'             => wp_create_nonce('mpt_nonce'),
        'is_mobile'         => wp_is_mobile(),
        'theme_path'        => MPT_THEME_URI,
        'is_cart'           => class_exists('WooCommerce') ? is_cart() : false,
        'is_checkout'       => class_exists('WooCommerce') ? is_checkout() : false,
        'is_product'        => class_exists('WooCommerce') ? is_product() : false,
        'currency_symbol'   => class_exists('WooCommerce') ? get_woocommerce_currency_symbol() : '$',
        'rtl'               => is_rtl(),
        'dark_mode'         => get_theme_mod('dark_mode_enable', false),
    ]);
    
    // Comment Reply
    if (is_singular() && comments_open() && get_option('thread_comments')) {
        wp_enqueue_script('comment-reply');
    }
    
    // Remove Block Library CSS
    if (!is_admin()) {
        wp_dequeue_style('wp-block-library');
        wp_dequeue_style('wp-block-library-theme');
        wp_dequeue_style('wc-block-style');
    }
}
add_action('wp_enqueue_scripts', 'mpt_enqueue_assets');

/**
 * Admin Assets
 */
function mpt_admin_assets($hook) {
    wp_enqueue_style('mpt-admin', MPT_ASSETS_URI . '/css/admin.css', [], MPT_VERSION);
    wp_enqueue_script('mpt-admin', MPT_ASSETS_URI . '/js/admin.js', ['jquery'], MPT_VERSION, true);
    
    // Theme Options Page
    if ('appearance_page_mpt-theme-options' === $hook) {
        wp_enqueue_media();
        wp_enqueue_style('wp-color-picker');
        wp_enqueue_script('wp-color-picker');
        wp_enqueue_script('mpt-theme-options', MPT_ASSETS_URI . '/js/theme-options.js', ['jquery', 'wp-color-picker'], MPT_VERSION, true);
    }
}
add_action('admin_enqueue_scripts', 'mpt_admin_assets');

