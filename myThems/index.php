// Load More Posts
function mpt_load_more_posts() {
    check_ajax_referer('mpt_nonce', 'nonce');
    
    $paged = isset($_POST['page']) ? intval($_POST['page']) : 2;
    $post_type = isset($_POST['post_type']) ? sanitize_text_field($_POST['post_type']) : 'post';
    $category = isset($_POST['category']) ? intval($_POST['category']) : '';
    $tag = isset($_POST['tag']) ? sanitize_text_field($_POST['tag']) : '';
    
    $args = [
        'post_type'      => $post_type,
        'post_status'    => 'publish',
        'paged'          => $paged,
        'posts_per_page' => get_option('posts_per_page'),
    ];
    
    if ($category) {
        $args['cat'] = $category;
    }
    
    if ($tag) {
        $args['tag'] = $tag;
    }
    
    $query = new WP_Query($args);
    
    if ($query->have_posts()) :
        while ($query->have_posts()) : $query->the_post();
            get_template_part('template-parts/content', get_post_type());
        endwhile;
        wp_reset_postdata();
    else :
        echo '<div class="no-more-posts alert alert-info">' . __('No more posts to load', 'mpt') . '</div>';
    endif;
    
    wp_die();
}
add_action('wp_ajax_mpt_load_more', 'mpt_load_more_posts');
add_action('wp_ajax_nopriv_mpt_load_more', 'mpt_load_more_posts');

