// Protected Content Shortcode
function mpt_protected_content_shortcode($atts, $content = null) {
    $atts = shortcode_atts([
        'role'   => '',
        'message' => __('This content is restricted. Please login to view.', 'mpt'),
        'class'  => '',
    ], $atts);
    
    if (is_user_logged_in()) {
        if ($atts['role']) {
            $user = wp_get_current_user();
            $roles = array_map('trim', explode(',', $atts['role']));
            
            $has_role = false;
            foreach ($roles as $role) {
                if (in_array($role, (array) $user->roles)) {
                    $has_role = true;
                    break;
                }
            }
            
            if ($has_role) {
                return '<div class="protected-content ' . esc_attr($atts['class']) . '">' . do_shortcode($content) . '</div>';
            } else {
                return '<div class="protected-content-message alert alert-warning ' . esc_attr($atts['class']) . '">' . esc_html($atts['message']) . '</div>';
            }
        } else {
            return '<div class="protected-content ' . esc_attr($atts['class']) . '">' . do_shortcode($content) . '</div>';
        }
    } else {
        return '<div class="protected-content-message alert alert-warning ' . esc_attr($atts['class']) . '">' . esc_html($atts['message']) . '</div>';
    }
}
