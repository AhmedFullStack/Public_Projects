            'privacy'  => ['title' => 'Privacy Policy', 'template' => ''],
            'terms'    => ['title' => 'Terms & Conditions', 'template' => ''],
        ];
        
        foreach ($pages as $key => $page) {
            if (!get_page_by_title($page['title'])) {
                $page_id = wp_insert_post([
