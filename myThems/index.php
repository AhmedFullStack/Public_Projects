        if ($categories) {
            echo '<li class="breadcrumb-item"><a href="' . get_category_link($categories[0]->term_id) . '">' . $categories[0]->name . '</a></li>';
        }
        if (is_single()) {
            echo '<li class="breadcrumb-item active" aria-current="page">' . get_the_title() . '</li>';
        }
    } elseif (is_page()) {
        echo '<li class="breadcrumb-item active" aria-current="page">' . get_the_title() . '</li>';
    } elseif (is_search()) {
        echo '<li class="breadcrumb-item active" aria-current="page">' . __('Search Results', 'mpt') . '</li>';
    } elseif (is_404()) {
        echo '<li class="breadcrumb-item active" aria-current="page">' . __('404 Not Found', 'mpt') . '</li>';
    } elseif (is_archive()) {
        echo '<li class="breadcrumb-item active" aria-current="page">' . get_the_archive_title() . '</li>';
    }
    
    echo '</ol>';
    echo '</nav>';
}

// Pagination
function mpt_pagination() {
    global $wp_query;
    
    $big = 999999999;
    
    $pages = paginate_links([
        'base'      => str_replace($big, '%#%', esc_url(get_pagenum_link($big))),
        'format'    => '?paged=%#%',
        'current'   => max(1, get_query_var('paged')),
        'total'     => $wp_query->max_num_pages,
        'type'      => 'array',
        'prev_text' => '&laquo;',
        'next_text' => '&raquo;',
        'mid_size'  => 2,
    ]);
    
    if (is_array($pages)) {
        echo '<nav class="pagination" aria-label="Pagination">';
        echo '<ul class="pagination-list">';
        
        foreach ($pages as $page) {
            $active = strpos($page, 'current') !== false ? ' active' : '';
            echo '<li class="page-item' . $active . '">' . str_replace(['page-numbers', 'span'], ['page-link', 'a'], $page) . '</li>';
        }
        
        echo '</ul>';
        echo '</nav>';
    }
}

