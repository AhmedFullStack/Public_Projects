// Live Search
function mpt_live_search() {
    check_ajax_referer('mpt_nonce', 'nonce');
    
    $search_term = sanitize_text_field($_POST['search_term']);
    
    if (empty($search_term)) {
        wp_send_json_error(['message' => __('Please enter search term', 'mpt')]);
    }
    
    $args = [
        'post_type'      => ['post', 'page', 'product'],
        'post_status'    => 'publish',
        's'              => $search_term,
        'posts_per_page' => 8,
    ];
    
    $query = new WP_Query($args);
    
    ob_start();
    
    if ($query->have_posts()) :
        echo '<ul class="live-search-results">';
        while ($query->have_posts()) : $query->the_post();
            ?>
            <li>
                <a href="<?php the_permalink(); ?>">
                    <?php if (has_post_thumbnail()) : ?>
                        <div class="search-result-thumb">
                            <?php the_post_thumbnail('thumbnail'); ?>
                        </div>
                    <?php endif; ?>
                    <div class="search-result-content">
                        <h4><?php the_title(); ?></h4>
                        <p><?php echo wp_trim_words(get_the_excerpt(), 15); ?></p>
                        <span class="search-result-type"><?php echo get_post_type_object(get_post_type())->labels->singular_name; ?></span>
                    </div>
                </a>
            </li>
            <?php
        endwhile;
        echo '</ul>';
        
        if ($query->found_posts > 8) :
            ?>
            <div class="view-all-results">
                <a href="<?php echo home_url('/?s=' . urlencode($search_term)); ?>">
                    <?php printf(__('View all %d results', 'mpt'), $query->found_posts); ?>
                </a>
            </div>
            <?php
        endif;
        
    else :
        echo '<div class="no-results">' . __('No results found', 'mpt') . '</div>';
    endif;
    
    wp_reset_postdata();
    
    $html = ob_get_clean();
    
    wp_send_json_success(['html' => $html]);
}
add_action('wp_ajax_mpt_live_search', 'mpt_live_search');
