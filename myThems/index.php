        }
        
        // Set homepage and blog page
        $homepage = get_page_by_title('Home');
        $blogpage = get_page_by_title('Blog');
        
        if ($homepage) {
            update_option('page_on_front', $homepage->ID);
            update_option('show_on_front', 'page');
